#!/bin/sh
# Builds the core's package, 86box.chimeraCore: the sandboxed core
# (core.wbx), what the frontend is told about it (waterbox.config,
# file_slots.json, default_keybinds.json), the texts a person reads
# (languages/), and the licences of everything compiled into it.
#
# Usage: waterbox/build-package.sh -m <miniBox checkout> [-o <out folder>] [-r <chimera checkout>]
#
#   -o   where the package is written (default build/Cores of this repository)
#   -r   a Chimera checkout: the package goes to its build/Cores instead
#        (the publish job's way; never into a checkout someone else works in)
#
# miniBox must be built, with its C++ guest toolchain (docs/BUILDING.md).
# JOBS (default 4) is how many compilers run at once.
set -eu
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/.." && pwd)"
mb="${MINIBOX_DIR:-}"
out=""
chimera_root=""
while getopts "m:o:r:" opt; do
	case "$opt" in
		m) mb="$OPTARG" ;;
		o) out="$OPTARG" ;;
		r) chimera_root="$OPTARG" ;;
		*) exit 2 ;;
	esac
done
if [ -n "$chimera_root" ]; then
	chimera_root="$(cd "$chimera_root" && pwd)"
	[ -n "$mb" ] || mb="$chimera_root/extern/chimera-common-minibox"
	[ -n "$out" ] || out="$chimera_root/build/Cores"
fi
[ -n "$mb" ] && [ -d "$mb" ] || { echo "say where miniBox is: -m <miniBox checkout>, or MINIBOX_DIR" >&2; exit 2; }
mb="$(cd "$mb" && pwd)"
[ -n "$out" ] || out="$root/build/Cores"
mkdir -p "$out"
out="$(cd "$out" && pwd)"

# the native build: the table exporter the declaration is generated by
[ -f "$root/build/meson-native/build.ninja" ] || meson setup "$root/build/meson-native" "$root" "-Dminibox_dir=$mb"
ninja -C "$root/build/meson-native" -j "${JOBS:-4}" list-machines
# the declaration is generated from the pinned 86Box's own tables, and the
# one in the repository must be what the generator writes now
python3 "$root/tools/gen-config.py" "$root/build/meson-native/list-machines" "$here/chimera-input.c" \
	"$root/build/waterbox.config.generated"
if ! cmp -s "$root/build/waterbox.config.generated" "$here/waterbox.config"; then
	echo "waterbox/waterbox.config is not what tools/gen-config.py writes from this 86Box; run:" >&2
	echo "  python3 tools/gen-config.py build/meson-native/list-machines waterbox/chimera-input.c waterbox/waterbox.config" >&2
	exit 1
fi

# the guest
[ -f "$root/build/meson-guest/build.ninja" ] || sh "$here/setup-guest.sh" -m "$mb"
ninja -C "$root/build/meson-guest" -j "${JOBS:-4}" core.wbx
sh "$mb/source/guest/check-wbx.sh" "$root/build/meson-guest/core.wbx"

staging="$root/build/package-staging"
rm -rf "$staging"
mkdir -p "$staging"
cp "$root/build/meson-guest/core.wbx" "$staging/core.wbx"
cp "$here/waterbox.config" "$here/default_keybinds.json" "$here/file_slots.json" "$staging/"
# the texts a person reads, a table per language (chimera docs/translations.md)
cp -r "$here/languages" "$staging/languages"
# the terms travel with the binary (waterbox/package-licenses.json)
python3 "$mb/source/guest/package-licenses.py" "$root" "$staging"

# ---- version: the commit, and that commit's date in UTC ----
core_version="${CORE_VERSION:-}"
if [ -z "$core_version" ]; then
	if commit="$(git -C "$root" rev-parse --short=12 HEAD 2>/dev/null)"; then
		git -C "$root" diff --quiet HEAD -- . ':(exclude)extern/86box' 2>/dev/null || commit="$commit-dirty"
		core_version="$commit+local"
	else
		core_version="unversioned+local"
	fi
fi
core_version_date="$(TZ=UTC git -C "$root" log -1 --date=format-local:%Y-%m-%dT%H:%M:%SZ --format=%cd HEAD 2>/dev/null || true)"
python3 - "$staging/waterbox.config" "$core_version" "$core_version_date" <<'PYVER'
import json, sys
path, version, date = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    cfg = json.load(f)
cfg["version"] = version
if date:
    cfg["versionDate"] = date
with open(path, "w") as f:
    json.dump(cfg, f, indent=2, ensure_ascii=False)
    f.write("\n")
PYVER

# ---- provenance: what built this package ----
gccver="$(gcc -dumpfullversion)"
musl_version="$(cat "$mb/extern/musl/VERSION" 2>/dev/null || echo unknown)"
guest_kit="$(git -C "$mb" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)"
upstream_pin="$(git -C "$root/extern/86box" describe --tags --always 2>/dev/null || echo unknown)"
python3 - "$staging/build.json" "$core_version" "$gccver" "$musl_version" "$guest_kit" "$upstream_pin" <<'PYPROV'
import json, sys
path, version, gcc, musl, kit, pin = sys.argv[1:7]
json.dump({
    "version": version,
    "toolchain": {"compiler": "gcc " + gcc, "target": "x86_64-linux-musl", "musl": musl},
    "guestKit": {"name": "miniBox", "commit": kit},
    "upstream": {"name": "86Box", "pin": pin},
}, open(path, "w"), indent=2, sort_keys=True)
PYPROV

zip_path="$out/86box.chimeraCore"
rm -f "$zip_path"
# deterministic packaging: sorted entries, fixed timestamp/permissions, pinned
# compression - the package's SHA1 is the core's identity (movies cite it)
python3 - "$staging" "$zip_path" <<'PYEOF'
import hashlib, os, sys, tempfile, zipfile

staging, zip_path = sys.argv[1], sys.argv[2]
FIXED_DATE = (1980, 1, 1, 0, 0, 0)

def write_package(path):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for root, dirs, files in os.walk(staging):
            dirs.sort()
            for name in sorted(files):
                full = os.path.join(root, name)
                info = zipfile.ZipInfo(os.path.relpath(full, staging), date_time=FIXED_DATE)
                info.compress_type = zipfile.ZIP_DEFLATED
                info.create_system = 3
                info.external_attr = 0o644 << 16
                with open(full, "rb") as f:
                    z.writestr(info, f.read())

write_package(zip_path)
with tempfile.NamedTemporaryFile(suffix=".zip") as tmp:
    write_package(tmp.name)
    again = hashlib.sha1(open(tmp.name, "rb").read()).hexdigest()
first = hashlib.sha1(open(zip_path, "rb").read()).hexdigest()
if first != again:
    sys.exit(f"packaging is not deterministic: {first} then {again}")
print(f"package sha1 {first}")
PYEOF
echo "packaged -> $zip_path"
