#!/usr/bin/env python3
"""embed.py <build.sh> <XUB source> <out .c>

Builds the XTIDE Universal BIOS images the core carries (build.sh, from the
source revision xub.ref pins) and writes them as C arrays the platform layer
answers for (chimera-plat.c, chimera_builtin_rom). Each image must be the
one that was proved on 86Box's cards (docs/PLAN.md): its SHA-1 is pinned
here, so another assembler that writes other bytes stops the build instead
of putting an untested ROM in the package.
"""
import hashlib
import os
import subprocess
import sys
import tempfile

# name (as the core names a ROM file: its path in 86Box's ROM set, '/' as
# '_') -> the SHA-1 of the image proved on that card
IMAGES = {
    "hdd_xtide_ide_xt.bin": "1d1fc68f4bb8bb01a325994c151a9579e7bae154",
    "hdd_xtide_ide_at.bin": "28c3090c7d6a4a32cbafc08ce10f22ba34df46b1",
}


def main():
    build, src, out = sys.argv[1:4]
    with tempfile.TemporaryDirectory() as tmp:
        r = subprocess.run(["sh", build, src, tmp], capture_output=True, text=True)
        if r.returncode != 0:
            sys.exit("the XTIDE Universal BIOS did not build:\n" + r.stdout + r.stderr)
        images = {}
        for name, want in IMAGES.items():
            data = open(os.path.join(tmp, name), "rb").read()
            have = hashlib.sha1(data).hexdigest()
            if have != want:
                sys.exit("%s has SHA-1 %s, not %s, the image proved on 86Box's card "
                         "(another nasm? see waterbox/xtide-bios/xub.ref)" % (name, have, want))
            images[name] = data
    lines = ["/* GENERATED by waterbox/xtide-bios/embed.py from the XTIDE Universal BIOS",
             " * (GPL-2.0-or-later), revision 638: the ROMs of 86Box's XT-IDE cards. */",
             "#include <stddef.h>", "#include \"chimera.h\"", ""]
    table = []
    for i, (name, data) in enumerate(sorted(images.items())):
        lines.append("static const unsigned char rom%d[%d] = {" % (i, len(data)))
        for k in range(0, len(data), 16):
            lines.append("\t" + ", ".join("0x%02x" % b for b in data[k:k + 16]) + ",")
        lines.append("};")
        table.append('\t{ "%s", rom%d, sizeof rom%d, "%s" },' % (name, i, i, IMAGES[name]))
    lines.append("const struct chimera_rom chimera_builtin_roms[] = {")
    lines += table
    lines.append("\t{ NULL, NULL, 0, NULL }")
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
