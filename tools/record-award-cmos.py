#!/usr/bin/env python3
"""record-award-cmos.py: record each Award board's default CMOS settings block.

  record-award-cmos.py --runner build/meson-native/run-native --roms <folder> --write waterbox/award-cmos.h
  record-award-cmos.py --runner ... --roms <folder> --check waterbox/award-cmos.h
  record-award-cmos.py --runner ... --roms <folder> --print [--set name=value ...]

An Award BIOS keeps a block of its own settings in the CMOS past the
standard bytes (0x33 to 0x7F), with checksums of its own. When the CMOS is
empty it says "CMOS checksum error - Defaults loaded" and waits for F1; after
F1 it writes its default settings into that block, and into the standard
bytes the project's settings do not decide (its keyboard rate at 0x11, its
hard disk types, "detect" on the P/I-P55T2P4, at 0x19 and 0x1A). The core
writes both at power-on from waterbox/award-cmos.h, then the standard bytes
the settings decide (drives, equipment, memory) and their checksum (patch
0009), so the board starts without F1 (the owner, 2026-10-31).

This tool makes that header. For each board it runs the native reference
with the CMOS left empty (CHIMERA_86BOX_EMPTY_CMOS, so neither the standard
bytes nor a carried block are written), presses F1 at frame 1500, runs to
frame 2500 with no disk, and takes bytes 0x10-0x2D and 0x33-0x7F of the
CMOS the BIOS wrote. --roms is a folder of the package's ROM files under their ids, as
tools/pin-roms.py --copy makes it from the ROM set of 86Box (the owner's;
no ROM is in this repository). Each board's BIOS file is checked against
the SHA-1 the package pins, and its SHA-1 is written beside the block.

--write writes the header; --check records again and exits 1 when the header
holds other bytes; --print prints each block as hex (with --set, the board
is run with that setting changed: for finding out what the block depends
on).
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# board, processor, the BIOS file it reads (the firmware id)
BOARDS = [
    ("486sp3", "i486dx2/66666666", "machines_486sp3_awsi2737.bin"),
    ("p55t2p4", "pentium_p54c/133333333", "machines_p55t2p4_0207_j2.bin"),
]
STD_FIRST, STD_LAST = 0x10, 0x2D
FIRST, LAST = 0x33, 0x7F
F1_FRAME, FRAMES = 1500, 2500


def f1_key():
    # the button number of F1, from the controller's own table
    out = subprocess.run([sys.executable, os.path.join(ROOT, "tests", "keys.py"),
                          os.path.join(ROOT, "waterbox", "chimera-input.c"), "/dev/stdin"],
                         input="%d key F1 5\n" % F1_FRAME, capture_output=True, text=True, check=True)
    return out.stdout.split()


def pinned_sha1(fw_id):
    cfg = json.load(open(os.path.join(ROOT, "waterbox", "waterbox.config")))
    for f in cfg["firmware"]:
        if f["id"] == fw_id:
            return f.get("sha1")
    return None


def record(runner, roms, machine, cpu, extra):
    with tempfile.TemporaryDirectory() as tmp:
        cmos = os.path.join(tmp, "cmos.bin")
        args = [runner, os.path.join(tmp, "run"), "--roms", roms]
        # a setting given twice is read as the first: the changes come first
        for s in extra:
            args += ["--set", s]
        args += ["--set", "machine=" + machine, "--set", "cpu=" + cpu, "--set", "video=vga",
                 "--set", "memoryKB=16384", "--set", "floppyA=35_2hd", "--frames", str(FRAMES)]
        args += f1_key() + ["--dump-cmos", cmos]
        env = dict(os.environ, CHIMERA_86BOX_EMPTY_CMOS="1")
        r = subprocess.run(args, env=env, capture_output=True, text=True)
        if r.returncode != 0 or not os.path.isfile(cmos):
            sys.exit("%s: the run failed: %s" % (machine, (r.stderr or r.stdout).strip()[-300:]))
        data = open(cmos, "rb").read()
    if len(data) <= LAST:
        sys.exit("%s: the CMOS is %d bytes, not 128" % (machine, len(data)))
    block = data[FIRST:LAST + 1]
    if set(block) <= {0xFF}:
        sys.exit("%s: the BIOS wrote no settings block (did it take F1 at frame %d?)" % (machine, F1_FRAME))
    return data[STD_FIRST:STD_LAST + 1], block


def header(blocks):
    out = ["/* GENERATED by tools/record-award-cmos.py from each board's own BIOS. Do",
           " * not edit by hand: run the tool again (docs/BUILDING.md).",
           " *",
           " * The CMOS an Award BIOS writes after \"CMOS checksum error - Defaults",
           " * loaded\" and F1: its default settings block, bytes 0x%02X-0x%02X, with the" % (FIRST, LAST),
           " * block's own checksums, and the standard bytes 0x%02X-0x%02X as it left them." % (STD_FIRST, STD_LAST),
           " * chimera_cmos_power_on (cinterface.c) writes both at power-on, then the",
           " * standard bytes the settings decide, so the board starts without F1. */",
           "",
           "#define AWARD_STD_FIRST  0x%02X" % STD_FIRST,
           "#define AWARD_STD_LAST   0x%02X" % STD_LAST,
           "#define AWARD_CMOS_FIRST 0x%02X" % FIRST,
           "#define AWARD_CMOS_LAST  0x%02X" % LAST,
           "",
           "static const struct award_cmos {",
           "\tconst char *machine;",
           "\tconst char *bios_sha1; /* the BIOS file it was recorded from */",
           "\tunsigned char std[AWARD_STD_LAST - AWARD_STD_FIRST + 1];",
           "\tunsigned char block[AWARD_CMOS_LAST - AWARD_CMOS_FIRST + 1];",
           "} award_cmos[] = {"]
    def rows(b):
        return ["\t\t" + " ".join("0x%02x," % x for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    for machine, sha1, (std, block) in blocks:
        out.append("\t{ \"%s\", \"%s\", {" % (machine, sha1))
        out += rows(std)
        out.append("\t}, {")
        out += rows(block)
        out.append("\t} },")
    out += ["};", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runner", required=True)
    ap.add_argument("--roms", required=True)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write")
    g.add_argument("--check")
    g.add_argument("--print", action="store_true")
    ap.add_argument("--set", action="append", default=[])
    ap.add_argument("--board", action="append", help="only this board (by machine name)")
    a = ap.parse_args()
    if a.set and not a.print:
        sys.exit("--set is for --print only: the header is recorded with the settings above")

    blocks = []
    for machine, cpu, fw in BOARDS:
        if a.board and machine not in a.board:
            continue
        path = os.path.join(a.roms, fw)
        if not os.path.isfile(path):
            sys.exit("%s: no %s in %s" % (machine, fw, a.roms))
        sha1 = hashlib.sha1(open(path, "rb").read()).hexdigest()
        if sha1 != pinned_sha1(fw):
            sys.exit("%s: %s is not the file the package pins" % (machine, fw))
        blocks.append((machine, sha1, record(os.path.abspath(a.runner), os.path.abspath(a.roms), machine, cpu, a.set)))

    if a.print:
        for machine, sha1, (std, block) in blocks:
            print("%-8s %s | %s" % (machine, std.hex(" "), block.hex(" ")))
        return
    text = header(blocks)
    if a.write:
        with open(a.write, "w") as fh:
            fh.write(text)
        print("recorded %d boards into %s" % (len(blocks), a.write))
        return
    have = open(a.check).read() if os.path.isfile(a.check) else ""
    if have != text:
        print("%s holds other bytes than the boards' BIOS write now" % a.check)
        sys.exit(1)
    print("%d boards recorded again: the same bytes as %s" % (len(blocks), a.check))


if __name__ == "__main__":
    main()
